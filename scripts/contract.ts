// pnpm contract:generate | contract:check. Builds the api with a pool that never connects,
// renders its OpenAPI 3.1 document (keys sorted) and the client types from it. `check`
// compares them byte for byte with the committed copies and fails on drift.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";
import { buildApp } from "../apps/api/src/app.ts";

const CLIENT = join(import.meta.dirname, "..", "packages", "api-client");
const FILES = { contract: join(CLIENT, "openapi.json"), types: join(CLIENT, "src", "schema.ts") };

function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value === null || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((k) => [k, sortKeys((value as Record<string, unknown>)[k])]),
  );
}

const app = buildApp({ pool: undefined as never, publicOrigin: "http://127.0.0.1:3300" });
await app.ready();
const contract = `${JSON.stringify(sortKeys(app.swagger()), null, 2)}\n`;
await app.close();
const ast = await openapiTS(JSON.parse(contract));
const types = `// Generated by pnpm contract:generate from openapi.json. Do not edit.\n${astToString(ast)}`;
const fresh = { contract, types };

const mode = process.argv[2];
if (mode === "generate") {
  for (const key of ["contract", "types"] as const) writeFileSync(FILES[key], fresh[key]);
  console.log("contract:generate: wrote openapi.json and src/schema.ts");
} else if (mode === "check") {
  const read = (f: string) => {
    try {
      return readFileSync(f, "utf8");
    } catch {
      return undefined;
    }
  };
  const drifted = (["contract", "types"] as const).filter((k) => read(FILES[k]) !== fresh[k]);
  if (drifted.length) {
    console.error("API contract drift — run pnpm contract:generate and commit");
    for (const k of drifted)
      console.error(`  differs: ${FILES[k].slice(CLIENT.length - "packages/api-client".length)}`);
    process.exit(1);
  }
  console.log("contract:check: no drift");
} else {
  throw new Error("usage: contract.ts generate | check");
}
